import SwiftUI
import AppKit

struct ClipEntry: Identifiable, Codable {
    let id: UUID
    let date: Date
    let text: String?
    let png: Data?
    var pinned: Bool
    var isLink: Bool { text.map { $0.hasPrefix("https://") || $0.hasPrefix("http://") } ?? false }
}
final class ClipboardModel: ObservableObject {
    @Published var entries: [ClipEntry] = []
    @Published var search = ""
    @Published var message: String?
    @Published var paused = UserDefaults.standard.bool(forKey: "clipboardPaused") {
        didSet { UserDefaults.standard.set(paused, forKey: "clipboardPaused"); lastChange = NSPasteboard.general.changeCount }
    }
    @Published var persistent = UserDefaults.standard.bool(forKey: "clipboardPersistent") {
        didSet { UserDefaults.standard.set(persistent, forKey: "clipboardPersistent"); save() }
    }
    @Published var limit = max(10, min(200, UserDefaults.standard.object(forKey: "clipboardLimit") as? Int ?? 50)) {
        didSet {
            if limit < entries.filter(\.pinned).count { limit = oldValue; message = "Desfijá elementos antes de reducir el límite."; return }
            UserDefaults.standard.set(limit, forKey: "clipboardLimit"); trim(); save()
        }
    }
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?
    private let file = FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent("Library/Application Support/MiMac/clipboard.json")
    init() {
        if persistent, let data = try? Data(contentsOf: file), let items = try? JSONDecoder().decode([ClipEntry].self, from: data) { entries = items; trim() }
        if !persistent { try? FileManager.default.removeItem(at: file) }
        timer = Timer.scheduledTimer(withTimeInterval: 0.7, repeats: true) { [weak self] _ in self?.capture() }
    }
    func capture() {
        let board = NSPasteboard.general
        guard board.changeCount != lastChange else { return }
        lastChange = board.changeCount
        guard !paused else { return }
        let types = Set((board.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]) else { return }
        // Do not interpret file URLs as ordinary text.
        guard !types.contains(NSPasteboard.PasteboardType.fileURL.rawValue) else { return }
        var png: Data?
        if let image = NSImage(pasteboard: board), let tiff = image.tiffRepresentation, let rep = NSBitmapImageRep(data: tiff), let data = rep.representation(using: .png, properties: [:]), data.count <= 5_000_000 { png = data }
        let text = png == nil ? board.string(forType: .string) : nil
        guard png != nil || (text.map { !$0.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty && $0.utf8.count <= 200_000 } ?? false) else { return }
        if let existing = entries.firstIndex(where: { $0.text == text && $0.png == png }) {
            let item = entries.remove(at: existing); entries.insert(item, at: 0); save(); return
        }
        guard entries.filter(\.pinned).count < limit else { message = "El historial está lleno de elementos fijados. Desfijá uno para guardar más."; return }
        entries.insert(ClipEntry(id: UUID(), date: Date(), text: text, png: png, pinned: false), at: 0)
        trim(); save()
    }
    func trim() {
        while entries.count > limit {
            if let index = entries.lastIndex(where: { !$0.pinned }) { entries.remove(at: index) }
            else { break }
        }
    }
    func copy(_ entry: ClipEntry) {
        let board = NSPasteboard.general; board.clearContents()
        if let png = entry.png { board.setData(png, forType: .png) }
        else if let text = entry.text { board.setString(text, forType: .string) }
        lastChange = board.changeCount
        message = "Copiado. Pegalo con ⌘V en otra app."
    }
    func pin(_ entry: ClipEntry) {
        guard let index = entries.firstIndex(where: { $0.id == entry.id }) else { return }
        entries[index].pinned.toggle(); trim(); save()
    }
    func remove(_ entry: ClipEntry) { entries.removeAll { $0.id == entry.id }; save() }
    func clear() { entries.removeAll(); save(); message = "Historial vacío." }
    func save() {
        do {
            if persistent {
                try FileManager.default.createDirectory(at: file.deletingLastPathComponent(), withIntermediateDirectories: true)
                try JSONEncoder().encode(entries).write(to: file, options: .atomic)
                try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: file.path)
            } else if FileManager.default.fileExists(atPath: file.path) { try FileManager.default.removeItem(at: file) }
        } catch { message = "No se pudo guardar o borrar el historial en disco." }
    }
    var filtered: [ClipEntry] {
        let matches = entries.filter { search.isEmpty || ($0.text ?? "Imagen").localizedCaseInsensitiveContains(search) }
        return matches.filter(\.pinned) + matches.filter { !$0.pinned }
    }
}
struct ClipboardOptions: View {
    @ObservedObject var model: ClipboardModel
    var body: some View {
        VStack(alignment: .leading, spacing: 10) {
            Toggle("Pausar captura", isOn: $model.paused)
            Toggle("Conservar historial al cerrar", isOn: $model.persistent)
            Picker("Elementos a guardar", selection: $model.limit) { ForEach([10, 25, 50, 100, 200], id: \.self) { Text("\($0)").tag($0) } }
        }.toggleStyle(.switch)
    }
}
struct ClipboardView: View {
    @ObservedObject var model: ClipboardModel
    var body: some View {
        VStack(alignment: .leading, spacing: 12) {
            HStack {
                    Spacer()
                Button(model.paused ? "Reanudar" : "Pausar") { model.paused.toggle() }
                Button("Vaciar") { model.clear() }.disabled(model.entries.isEmpty)
            }
            TextField("Buscar texto o enlace", text: $model.search).textFieldStyle(.roundedBorder)
            if let message = model.message { Text(message).font(.caption).foregroundStyle(.gray) }
            if model.filtered.isEmpty { Text(model.paused ? "Captura pausada" : "Historial vacío").font(.caption).foregroundStyle(.gray).padding(.vertical, 15) }
            ForEach(model.filtered) { entry in
                HStack(spacing: 10) {
                    Button { model.copy(entry) } label: {
                        HStack(spacing: 10) {
                            if let png = entry.png, let image = NSImage(data: png) { Image(nsImage: image).resizable().scaledToFit().frame(width: 48, height: 40).clipShape(RoundedRectangle(cornerRadius: 6)) }
                            else { Image(systemName: entry.isLink ? "link" : "text.alignleft").foregroundStyle(.blue).frame(width: 30) }
                            VStack(alignment: .leading, spacing: 4) {
                                Text(entry.text ?? "Imagen").font(.system(size: 12)).lineLimit(3).multilineTextAlignment(.leading)
                                Text(entry.date.formatted(date: .omitted, time: .shortened)).font(.caption2).foregroundStyle(.gray)
                            }
                            Spacer(minLength: 0)
                        }.frame(maxWidth: .infinity, alignment: .leading).contentShape(Rectangle())
                    }.buttonStyle(.plain).help("Copiar para pegar con ⌘V")
                    Button { model.pin(entry) } label: { Image(systemName: entry.pinned ? "pin.fill" : "pin").foregroundStyle(entry.pinned ? .orange : .gray) }.buttonStyle(.plain).help(entry.pinned ? "Desfijar" : "Fijar")
                    Button { model.remove(entry) } label: { Image(systemName: "xmark").foregroundStyle(.gray) }.buttonStyle(.plain).help("Quitar")
                }.padding(12).background(Color(white: 0.075), in: RoundedRectangle(cornerRadius: 14))
            }
        }
    }
}
